def render(s):
    lines = [
        f"{s['num']:02d}. {s['title']}",
        f"Исполнитель: {s['artist']}",
        f"Тональность: {s['key']}",
    ]
    if s["note"]:
        lines.append(f"Примечание: {s['note']}")
    lines += ["", "=" * 60, "", s["body"], "", "=" * 60, ""]
    return "\n".join(lines)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    # clean old txts
    for p in OUT.glob("*.txt"):
        p.unlink()

    index_lines = [
        "ГИТАРНЫЙ СБОРНИК — оглавление",
        "Слова и аккорды. Структура: Куплет / Припев / Бридж",
        "Где тональность не указана — оригинальная.",
        "",
        "-" * 60,
    ]

    for s in SONGS:
        path = OUT / s["filename"]
        path.write_text(render(s), encoding="utf-8")
        index_lines.append(
            f"{s['num']:02d}. [{s['key']:3}] {s['title']} — {s['artist']}"
        )
        index_lines.append(f"     → {s['filename']}")

    index_lines += ["", f"Всего песен: {len(SONGS)}", ""]
    (OUT / "00-OGLavlenie.txt").write_text("\n".join(index_lines), encoding="utf-8")
    print(f"Wrote {len(SONGS)} songs + index → {OUT}")


if __name__ == "__main__":
    main()
